def is_carom_fact(field, value):
    """caromTables 0 (none) and an unknown hasCarom say nothing the site shows, so they stay out."""
    if field == "caromTables":
        return isinstance(value, int) and not isinstance(value, bool) and value >= 1
    return value is True


def carom_tables(v):
    """The hall's carom table count, or None when it is known to have some but not how many."""
    return v.get("caromTables")


def offers_carom(v):
    """The app's Venue.offersCarom: a count of 1 or more, or hasCarom."""
    return carom_tables(v) is not None or v.get("hasCarom") is True


def open_countries(source):
    """From the app repo's countries.json beside the backup: the open countries' codes, and the
    fallback's, the country of a hall that names none, as the app reads it."""
    path = Path(source).with_name("countries.json")
    if not path.is_file():
        sys.exit(f"no countries.json beside {source}: --import takes the app repo's data/venues-backup.json")
    countries = json.loads(path.read_text(encoding="utf-8"))
    fallback = next(c["code"] for c in countries if c.get("fallback"))
    return {c["code"] for c in countries if c.get("open") is True}, fallback


def import_backup(source):
    raw = json.loads(Path(source).read_text(encoding="utf-8"))
    open_codes, fallback = open_countries(source)
    records = []
    for venue in raw:
        country = venue.get("country") or fallback
        # A closed country's halls stay in the app repo until it opens.
        if country not in open_codes:
            continue
        record = {}
        for field in PUBLIC_FIELDS:
            value = country if field == "country" else venue.get(field)
            if value is None or value == "":
                continue
            if field in CAROM_FIELDS and not is_carom_fact(field, value):
                continue
            if isinstance(value, str):
                value = DASHES.sub("-", value.strip())
            record[field] = value
        records.append(record)
    records.sort(key=lambda r: (r.get("sortOrder", 10**9), r.get("id", "")))
    return json.dumps(records, ensure_ascii=False, indent=2) + "\n"


def load_venues(text=None):
    """The checked halls of data/venues.json, or of an import's text before anything is written."""
    venues = json.loads(DATA.read_text(encoding="utf-8") if text is None else text)
    errors, seen, country_of_city = [], set(), {}
    for v in venues:
        vid = v.get("id", "?")
        for field in ("id", "name", "city", "address"):
            if not isinstance(v.get(field), str) or not v[field].strip():
                errors.append(f"{vid}: missing {field}")
        if vid in seen:
            errors.append(f"{vid}: duplicate id")
        seen.add(vid)
        extra = sorted(set(v) - set(PUBLIC_FIELDS))
        if extra:
            errors.append(f"{vid}: non-public fields {extra}; refresh with --import, never by copying the backup")
        if v.get("city") not in CITIES:
            errors.append(f"{vid}: unknown city {v.get('city')!r}; add it to CITIES in tools/build_directory.py")
        country = v.get("country")
        if country not in COUNTRIES:
            errors.append(f"{vid}: unknown country {country!r}; add it to COUNTRIES in tools/build_directory.py")
        elif country_of_city.setdefault(v.get("city"), country) != country:
            errors.append(f"{vid}: {v.get('city')} is in {country_of_city[v.get('city')]} on another hall, "
                          f"not in {country}")
        website = v.get("website")
        if website is not None and not re.match(r"https?://[^\s\"<>]+$", website):
            errors.append(f"{vid}: website must be an http(s) URL")
        for field in CAROM_FIELDS:
            if field in v and not is_carom_fact(field, v[field]):
                errors.append(f"{vid}: {field} must be a count of 1 or more, or true; leave it out otherwise")
    if errors:
        what = "data/venues.json is invalid" if text is None else "the import is invalid; data/venues.json is unchanged"
        sys.exit(f"{what}:\n  " + "\n  ".join(errors))
    return venues


def group_by_city(venues):
    cities = {}
    for v in venues:
        cities.setdefault(v["city"], []).append(v)
    for halls in cities.values():
        # A to Z, so no hall leads a page for the number it was given.
        halls.sort(key=lambda v: (alphabetical_key(v["name"]), v["id"]))
    return cities


def country_of(halls):
    """A city's country. Every hall in a city names the same one; load_venues checks it."""
    return halls[0]["country"]


def by_country(cities):
    """Country code -> its cities and their halls, the country with the most halls first."""
    found = {}
    for city, halls in cities.items():
        found.setdefault(country_of(halls), {})[city] = halls
    order = sorted(found, key=lambda code: (-sum(len(h) for h in found[code].values()), COUNTRIES[code][1]))
    return {code: found[code] for code in order}


def area_of(address):
    """The part after the last comma, when it holds no digit: the district."""
    parts = [p.strip() for p in address.split(",")]
    if len(parts) < 2 or not parts[-1] or re.search(r"\d", parts[-1]):
        return None
    return parts[-1]


def areas_of(halls):
    found = []
    for v in halls:
        area = area_of(v["address"])
        if area and area not in found:
            found.append(area)
    return found


