def esc(text):
    """Safe in text and in double-quoted attributes; apostrophes stay readable."""
    return html.escape(str(text), quote=False).replace('"', "&quot;")


def fold(text):
    """Accent-free lowercase key, so Greek names sort alphabetically."""
    decomposed = unicodedata.normalize("NFD", text)
    return "".join(c for c in decomposed if not unicodedata.combining(c)).lower()


def plural_el(n):
    return f"{n} αίθουσα" if n == 1 else f"{n} αίθουσες"


def plural_en(n):
    return f"{n} hall" if n == 1 else f"{n} halls"


# ---------------------------------------------------------------- data

def import_backup(source):
    raw = json.loads(Path(source).read_text(encoding="utf-8"))
    records = []
    for venue in raw:
        record = {}
        for field in PUBLIC_FIELDS:
            value = venue.get(field)
            if value is None or value == "":
                continue
            if isinstance(value, str):
                value = DASHES.sub("-", value.strip())
            record[field] = value
        records.append(record)
    records.sort(key=lambda r: (r.get("sortOrder", 10**9), r.get("id", "")))
    return json.dumps(records, ensure_ascii=False, indent=2) + "\n"


def load_venues():
    venues = json.loads(DATA.read_text(encoding="utf-8"))
    errors, seen = [], set()
    for v in venues:
        vid = v.get("id", "?")
        for field in ("id", "name", "city", "address"):
            if not isinstance(v.get(field), str) or not v[field].strip():
                errors.append(f"{vid}: missing {field}")
        if vid in seen:
            errors.append(f"{vid}: duplicate id")
        seen.add(vid)
        extra = sorted(set(v) - set(PUBLIC_FIELDS))
        if extra:
            errors.append(f"{vid}: non-public fields {extra}; refresh with --import, never by copying the backup")
        if v.get("city") not in CITIES:
            errors.append(f"{vid}: unknown city {v.get('city')!r}; add it to CITIES in tools/build_directory.py")
        website = v.get("website")
        if website is not None and not re.match(r"https?://[^\s\"<>]+$", website):
            errors.append(f"{vid}: website must be an http(s) URL")
    if errors:
        sys.exit("data/venues.json is invalid:\n  " + "\n  ".join(errors))
    return venues


def group_by_city(venues):
    cities = {}
    for v in venues:
        cities.setdefault(v["city"], []).append(v)
    for halls in cities.values():
        halls.sort(key=lambda v: (v.get("sortOrder", 10**9), v["id"]))
    return cities


def area_of(address):
    """The part after the last comma, when it holds no digit: the district."""
    parts = [p.strip() for p in address.split(",")]
    if len(parts) < 2 or not parts[-1] or re.search(r"\d", parts[-1]):
        return None
    return parts[-1]


def areas_of(halls):
    found = []
    for v in halls:
        area = area_of(v["address"])
        if area and area not in found:
            found.append(area)
    return found


def phone_href(phone):
    digits = re.sub(r"[^\d+]", "", phone)
    return f"tel:{digits}" if len(re.sub(r"\D", "", digits)) >= 6 else None


