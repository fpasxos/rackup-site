def sitemap(cities):
    paths = ["", "en/", "support.html", "privacy.html", f"{EL_ROOT}/", f"{EN_ROOT}/"]
    for city in city_order(cities, "el"):
        slug = CITIES[city][0]
        paths += [f"{EL_ROOT}/{slug}/", f"{EN_ROOT}/{slug}/"]
    entries = "\n".join(f"  <url><loc>{url(p)}</loc></url>" for p in paths)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            f"{entries}\n</urlset>\n")


def home_with_counts(text, cities):
    """The homes are hand-written; only their data-count spans, city grid and store links are ours."""
    counts = {"venues": sum(len(h) for h in cities.values()), "cities": len(cities)}
    for key, value in counts.items():
        text, found = re.subn(rf'(<span data-count="{key}">)\d+(</span>)', rf"\g<1>{value}\g<2>", text)
        if not found:
            sys.exit(f'a home page has no <span data-count="{key}"> to update')
    return text


def city_grid(cities, lang):
    """Every city and its hall count, linked relative to the home of that language."""
    root = EL_ROOT if lang == "el" else EN_ROOT[len("en/"):]
    items = []
    for city in city_order(cities, lang):
        slug, name_el, _ = CITIES[city]
        n = len(cities[city])
        label = plural_el(n) if lang == "el" else plural_en(n)
        name = name_el if lang == "el" else city
        items.append(f'  <li><a href="{root}/{slug}/"><span class="city">{esc(name)}</span>'
                     f' <span class="count">{label}</span></a></li>')
    return '<ul class="city-grid">\n' + "\n".join(items) + "\n</ul>"


def home_with_city_grid(text, cities, lang):
    start, end = text.find(GRID_START), text.find(GRID_END)
    if start < 0 or end < start:
        sys.exit(f"a home page has no {GRID_START} ... {GRID_END} block for the city grid")
    return text[:start + len(GRID_START)] + "\n" + city_grid(cities, lang) + "\n" + text[end:]


def with_store_links(name, text):
    """Tags every store href on a hand-written page with that page's campaign."""
    campaign = campaign_for(HAND_PAGES[name])
    play = f'href="{esc(play_url(campaign))}"'
    apple = f'href="{esc(app_store_url(campaign))}"'
    text, plays = re.subn(r'href="https://play\.google\.com/[^"]*"', lambda _: play, text)
    text, apples = re.subn(r'href="https://apps\.apple\.com/[^"]*"', lambda _: apple, text)
    if not plays or not apples:
        sys.exit(f"{name} has no store links to tag; drop it from HAND_PAGES if that is intended")
    return text


def render():
    cities = group_by_city(load_venues())
    files = {ROOT / "sitemap.xml": sitemap(cities)}
    for name in HAND_PAGES:
        text = (ROOT / name).read_text(encoding="utf-8")
        if name in HOMES:
            text = home_with_city_grid(home_with_counts(text, cities), cities, HOMES[name])
        files[ROOT / name] = with_store_links(name, text)
    for lang, root in (("el", EL_ROOT), ("en", EN_ROOT)):
        files[ROOT / root / "index.html"] = index_page(cities, lang)
        for city, halls in cities.items():
            files[ROOT / root / CITIES[city][0] / "index.html"] = city_page(city, halls, cities, lang)
    for path, text in files.items():
        if DASHES.search(text):
            sys.exit(f"{path.relative_to(ROOT)} would contain an en or em dash; fix the copy or the data")
    return files


def stale_generated_dirs(files):
    """City folders this script made earlier for a city that has since gone."""
    stale = []
    for root in (EL_ROOT, EN_ROOT):
        base = ROOT / root
        if not base.is_dir():
            continue
        for child in base.iterdir():
            page_file = child / "index.html"
            if (child.is_dir() and page_file not in files and page_file.is_file()
                    and MARKER in page_file.read_text(encoding="utf-8")):
                stale.append(child)
    return stale


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--import", dest="source", metavar="PATH",
                        help="refresh data/venues.json from the app repo's data/venues-backup.json")
    parser.add_argument("--check", action="store_true", help="exit 1 if any page is out of date")
    args = parser.parse_args()

    if args.source:
        DATA.parent.mkdir(parents=True, exist_ok=True)
        DATA.write_text(import_backup(args.source), encoding="utf-8", newline="\n")
        print(f"Imported {args.source} into {DATA.relative_to(ROOT)}")

    files = render()
    stale = stale_generated_dirs(files)
    if args.check:
        outdated = [p for p, t in files.items() if not p.is_file() or p.read_text(encoding="utf-8") != t]
        for p in outdated + stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        sys.exit(1 if outdated or stale else 0)

    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    for folder in stale:
        shutil.rmtree(folder)
        print(f"removed {folder.relative_to(ROOT)}")
    cities = group_by_city(load_venues())
    print(f"Wrote {len(files) - 1 - len(HAND_PAGES)} directory pages for {sum(map(len, cities.values()))} halls "
          f"in {len(cities)} cities, plus sitemap.xml, the counts in index.html and the store links "
          f"in {' and '.join(HAND_PAGES)}")


if __name__ == "__main__":
    main()
