def hall_item(v, lang):
    parts = [f'<li class="hall" id="{esc(v["id"])}">',
             f'  <h2{lang_attr(v["name"], lang)}>{esc(v["name"])}</h2>',
             f'  <p class="addr"{lang_attr(v["address"], lang)}>{esc(v["address"])}</p>']
    phone = v.get("phone")
    if phone:
        label = "Τηλέφωνο" if lang == "el" else "Phone"
        href = phone_href(phone)
        shown = f'<a href="{esc(href)}">{esc(phone)}</a>' if href else esc(phone)
        parts.append(f'  <p class="contact">{label}: {shown}</p>')
    website = v.get("website")
    if website:
        label = "Ιστοσελίδα" if lang == "el" else "Website"
        host = re.sub(r"^https?://(www\.)?", "", website).rstrip("/")
        parts.append(f'  <p class="contact">{label}: <a href="{esc(website)}" rel="noopener">{esc(host)}</a></p>')
    if offers_carom(v):
        parts.append(carom_chip(v, lang))
    parts.append("</li>")
    return "\n".join(parts)


def places(areas, halls, lang):
    """Up to four districts, closed with "elsewhere" unless they hold every hall."""
    shown = areas[:4]
    words = [esc(a) if lang == "el" else in_greek(a) for a in shown]
    if any(area_of(v["address"]) not in shown for v in halls):
        words.append("αλλού" if lang == "el" else "elsewhere")
    return joined(words, lang) if words else ""


