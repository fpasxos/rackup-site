def city_order(cities, lang):
    def key(city):
        name = CITIES[city][1] if lang == "el" else city
        return (-len(cities[city]), fold(name))
    return sorted(cities, key=key)


# The carom ball, as the home's 3-cushion chip draws it.
CAROM_BALL = '<span class="ball cr" aria-hidden="true"></span>'


def carom_by_city(cities):
    """City -> its halls known to have carom tables, in the city page's order; cities with none left out."""
    found = {}
    for city, halls in cities.items():
        mine = [v for v in halls if offers_carom(v)]
        if mine:
            found[city] = mine
    return found


def carom_link(href, text):
    """The chip under a directory page's lead that opens the carom page."""
    return f'<p class="tags"><a class="chip chip-link" href="{href}">{CAROM_BALL}{text}</a></p>'


def carom_chip(v, lang):
    """A hall's carom chip: the count when it is known, the word alone when it is not."""
    n = carom_tables(v)
