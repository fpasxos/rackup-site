def joined(words, lang):
    """A, B and C, or Α, Β και Γ."""
    last = " και " if lang == "el" else " and "
    return words[0] if len(words) == 1 else ", ".join(words[:-1]) + last + words[-1]


def lang_attr(text, lang):
    """lang="el" on Greek text in an English page, so a screen reader reads it in Greek."""
    return ' lang="el"' if lang == "en" and GREEK_TEXT.search(text) else ""


def in_greek(text):
    """Escaped text for an English page, inside a lang="el" span when it is Greek."""
    return f'<span lang="el">{esc(text)}</span>' if GREEK_TEXT.search(text) else esc(text)


